-- zaliha u centru i krvnoj grupi
CREATE VIEW CenterBloodStock AS
SELECT quantity.*, CASE WHEN quantity.quantity < quantity.CriticalThreshold THEN 'CRITICAL'
                        WHEN quantity.quantity < quantity.LowThreshold THEN 'LOW'
                        ELSE 'OK' END AS StockLevel 
FROM (
    SELECT c.centerID, b.BloodType, 
                        COUNT(d.DoseID)::INT as Quantity, 
                        COALESCE(SUM(d.AmountMl), 0)::INT AS TotalMl, 
                        COALESCE(t.LowThreshold, (SELECT ConstValue::INT FROM Constants WHERE ConstKey = 'DEFAULT_LOW_THRESHOLD'))::INT AS LowThreshold,
                        COALESCE(t.CriticalThreshold, (SELECT ConstValue::INT FROM Constants WHERE ConstKey = 'DEFAULT_CRITICAL_THRESHOLD'))::INT AS CriticalThreshold
    FROM Center c CROSS JOIN BloodTypeRef b LEFT JOIN CenterBloodThreshold t ON t.centerID = c.centerID AND t.BloodType = b.BloodType
    LEFT JOIN BloodDose d ON d.centerID = c.CenterID AND d.BloodType = b.BloodType AND d.DoseStatus = 'STOCK' AND d.ExpirationDate > now()
    GROUP BY c.centerID, b.BloodType, t.LowThreshold, t.CriticalThreshold
) quantity;


-- ukupno stanje u svim centrima
CREATE VIEW BloodStockTotal AS 
SELECT quantity.* , CASE WHEN quantity.quantity < quantity.CriticalThreshold THEN 'CRITICAL'
                        WHEN quantity.quantity < quantity.LowThreshold THEN 'LOW'
                        ELSE 'OK' END AS StockLevel 
FROM (
    SELECT BloodType, SUM(Quantity)::INT AS Quantity, SUM(LowThreshold)::INT as LowThreshold, SUM(CriticalThreshold)::INT AS CriticalThreshold 
    FROM CenterBloodStock GROUP BY BloodType
) quantity;

-- odziv na hitne pozive
CREATE VIEW UrgentCallResponse AS
SELECT c.CallID, c.CenterID, c.BloodType, c.Status, c.SentAt,
        (SELECT COUNT(*) FROM UrgentCallRecipientLog l WHERE l.CallID = c.CallID)::INT AS Recipients,
        (SELECT COUNT(DISTINCT a.DonorID) FROM Appointment a WHERE a.UrgentCallID = c.CallID)::INT AS Reserved,
        (SELECT COUNT(DISTINCT a.DonorID) FROM Appointment a WHERE a.UrgentCallID = c.CallID AND a.AppointmentStatus = 'FINISHED')::INT AS Donated
FROM UrgentCall c;

-- statistika akcija
CREATE VIEW ActionStats AS
SELECT f.actionID, f.actionName, f.Status, 
        COUNT(a.AppointmentID) FILTER (WHERE a.AppointmentStatus <> 'CANCELLED')::INT AS Registered,
        COUNT(a.AppointmentID) FILTER (WHERE a.AppointmentStatus IN ('ARRIVED', 'SCREENING', 'DONATING', 'FINISHED', 'REJECTED'))::INT AS Attended,
        COUNT(a.AppointmentID) FILTER (WHERE a.AppointmentStatus = 'FINISHED')::INT  AS Donated,
        COUNT(a.AppointmentID) FILTER (WHERE a.AppointmentStatus = 'REJECTED')::INT  AS Rejected
FROM FieldAction f LEFT JOIN Appointment a ON a.ActionID = f.ActionId GROUP BY f.ActionID, f.ActionName, f.Status;

-- prosjecna potrosnja i procjena dana do nestasice
CREATE VIEW StockForecast AS
SELECT s.CenterID, s.BloodType, s.Quantity, s.StockLevel, ROUND(COALESCE(u.Issued, 0) / 30.0, 2) AS DailyAvgUse,
        CASE WHEN COALESCE(u.Issued, 0) = 0 THEN NULL
        ELSE ROUND(s.Quantity / (u.Issued / 30), 1) END AS DaysToShortage
FROM CenterBloodStock s 
LEFT JOIN (SELECT CenterID, BloodType, COUNT(*) AS Issued
            FROM BloodDose WHERE DoseStatus = 'ISSUED' AND IssuedAt > now() - INTERVAL '30 days'
            GROUP BY CenterID, BloodType
) u ON u.CenterID = s.CenterID AND u.BloodType = s.BloodType;
