CREATE DATABASE KrvnaVeza;

CREATE TABLE Constants (
    ConstKey TEXT PRIMARY KEY,
    ConstValue TEXT,
);

-- Tu insert konstante

CREATE TABLE User (
    UserID BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    FirstName TEXT NOT NULL,
    LastName TEXT NOT NULL,
    DoB DATE,
    Sex CHAR(1),
    Residence TEXT,
    Role VARCHAR(11) NOT NULL,

    CONSTRAINT sex_val CHECK (Sex IN ('M', 'F'))
    CONSTRAINT role_val CHECK (Role IN "ADMIN", "DONOR", "ORGANIZATOR", "STAFF")
);

CREATE TABLE Center (
    CenterID INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    CenterName TEXT NOT NULL,
    Address TEXT NOT NULL,
    Lat REAL NOT NULL,
    Lng REAL NOT NULL,

    -- dodat toleranciju jer je float?
    CONSTRAINT lat_range CHECK (Lat BETWEEN -90.0 AND 90.0),
    CONSTRAINT lng_range CHECK (Lng BETWEEN -180.0 AND 180.0)
);

CREATE TABLE Donor (
    UserID BIGINT PRIMARY KEY,
    PhoneNumber VARCHAR(16),
    EmailAddress TEXT,
    BloodType VARCHAR(3),
    DonationsMade SMALLINT,

    CONSTRAINT userid_fk FOREIGN KEY (UserID) REFERENCES User(UserID),
    CONSTRAINT bloodtype_val CHECK (BloodType IN ("AB+", "AB-", "A+", "A-", "B+", "B-", "O+", "O-")),
    CONSTRAINT donationsmade_nonzero CHECK (DonationsMade >= 0)
);

CREATE TABLE Staff (
    UserID BIGINT PRIMARY KEY,
    CenterID INTEGER NOT NULL,

    CONSTRAINT userid_fk FOREIGN KEY (UserID) REFERENCES User(UserID),
    CONSTRAINT centerid_fk FOREIGN KEY (CenterID) REFERENCES Center(CenterID)
);

CREATE TABLE CenterWorktime (
    CenterID INTEGER PRIMARY KEY,
    WorkStart TIMETZ NOT NULL,
    WorkEnd TIMETZ NOT NULL,
    DayOfWeek VARCHAR(9) NOT NULL,

    CONSTRAINT centerid_fk FOREIGN KEY (CenterID) REFERENCES Center(CenterID),
    CONSTRAINT work_time CHECK (WorkEnd > WorkStart),
    CONSTRAINT dow_val CHECK (DayOfWeek IN ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"))
);

CREATE TABLE CenterAppointment (
    CenterID INTEGER PRIMARY KEY,
    DayOfWeek VARCHAR(9) NOT NULL,
    CenterAppointmentStart TIMETZ NOT NULL,
    CenterAppointmentEnd TIMETZ NOT NULL,
    Capacity SMALLINT NOT NULL,

    CONSTRAINT centerid_fk FOREIGN KEY (CenterID) REFERENCES Center(CenterID),
    CONSTRAINT dow_val CHECK (DayOfWeek IN ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"))
    CONSTRAINT app_time CHECK (CenterAppointmentEnd > CenterAppointmentStart),
    CONSTRAINT capacity_nonnegative CHECK (capacity >= 0)
);

CREATE TABLE Action (
    ActionID BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    ActionName TEXT NOT NULL,
    ActionStart TIMESTAMP NOT NULL,
    ActionEnd TIMESTAMP NOT NULL,
    Address TEXT NOT NULL,
    Lat REAL NOT NULL,
    Lng REAL NOT NULL,
    Capacity SMALLINT NOT NULL,
    TraumaTeam TEXT NOT NULL,

    CONSTRAINT action_time CHECK (ActionEnd > ActionStart),
    CONSTRAINT lat_range CHECK (Lat BETWEEN -90.0 AND 90.0),
    CONSTRAINT lng_range CHECK (Lng BETWEEN -180.0 AND 180.0),
    CONSTRAINT capacity_nonnegative CHECK (capacity >= 0)
);

CREATE TABLE Appointment (
    AppointmentID BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    UserID BIGINT PRIMARY KEY,
    AppointmentStart TIMESTAMP NOT NULL,
    AppointmentEnd TIMESTAMP NOT NULL,
    AppointmentStatus VARCHAR(10) NOT NULL,

    CONSTRAINT userid_fk FOREIGN KEY (UserID) REFERENCES User(UserID),
    CONSTRAINT action_time CHECK (AppointmentEnd > AppointmentStart),
    CONSTRAINT appointment_status_val CHECK (AppointmentStatus IN (("ARRIVED", "CANCELLED", "DONATING", "FINISHED", "NOTARRIVED", "REJECTED", "RESERVED", "SCREENING"))
);

CREATE TABLE SelfAssessment (
    AppointmentID BIGINT PRIMARY KEY,
    UserID BIGINT PRIMARY KEY,
    Responses TEXT, -- treba ih dodat sve

    CONSTRAINT appointmentid_fk FOREIGN KEY (AppointmentID) REFERENCES Appointment(AppointmentID),
    CONSTRAINT userid_fk FOREIGN KEY (UserID) REFERENCES User(UserID)
);

CREATE TABLE DonorDeferral (
    UserID BIGINT PRIMARY KEY,
    Until TIMESTAMP NOT NULL,
    Reason TEXT,
    Infinite BOOLEAN NOT NULL,

    CONSTRAINT userid_fk FOREIGN KEY (UserID) REFERENCES User(UserID)
);

CREATE TABLE BloodDose (
    AppointmentID BIGINT PRIMARY KEY,
    UserID BIGINT PRIMARY KEY,
    DateOfCollection TIMESTAMP NOT NULL,
    BloodType VARCHAR(3) NOT NULL,
    Amount REAL NOT NULL,
    ExpirationDate TIMESTAMP NOT NULL,
    DoseStatus VARCHAR(9) NOT NULL,
    TestResult TEXT, -- ?
    IssuedTo TEXT,
    Barcode TEXT,

    CONSTRAINT appointmentid_fk FOREIGN KEY (AppointmentID) REFERENCES Appointment(AppointmentID),
    CONSTRAINT userid_fk FOREIGN KEY (UserID) REFERENCES User(UserID),
    CONSTRAINT bloodtype_val CHECK (BloodType IN ("AB+", "AB-", "A+", "A-", "B+", "B-", "O+", "O-")),
    CONSTRAINT testresult_val CHECK (TestResult IN ("COLLECTED", "ISSUED", "DISCARDED", "STOCK", "TESTING")),
    CONSTRAINT collection_expiration CHECK (ExpirationDate > TimeOfCollection)
);

CREATE TABLE CenterBloodThreshold (
    CenterID INTEGER PRIMARY KEY,
    BloodType VARCHAR(3) PRIMARY KEY,
    LowThreshold SMALLINT NOT NULL,
    CriticalThreshold SMALLINT NOT NULL,

    CONSTRAINT centerid_fk FOREIGN KEY (CenterID) REFERENCES Center(CenterID),
    CONSTRAINT bloodtype_val CHECK (BloodType IN ("AB+", "AB-", "A+", "A-", "B+", "B-", "O+", "O-")),
    CONSTRAINT threshold_ordering CHECK (CriticalThreshold < LowThreshold),
    CONSTRAINT threshold_nonnegative CHECK ((CriticalThreshold > 0) AND (LowThreshold > 0))
);

CREATE TABLE CenterBloodStock (
    CenterID INTEGER PRIMARY KEY,
    BloodType VARCHAR(3) PRIMARY KEY,
    Amount INTEGER NOT NULL,

    CONSTRAINT centerid_fk FOREIGN KEY (CenterID) REFERENCES Center(CenterID),
    CONSTRAINT bloodtype_val CHECK (BloodType IN ("AB+", "AB-", "A+", "A-", "B+", "B-", "O+", "O-")),
    CONSTRAINT amount_nonnegative CHECK (Amount >= 0)
);
